// Measures computer strength: 2-player head-to-head win rates (seats alternate), and the
// Hard computer's win rate at a 4-player table of one Hard + three of a level.
// Run: node tools/measure-levels.js [games per pairing]   Writes js/strength-data.js.
const fs = require('fs');
const path = require('path');
const E = require('../js/engine.js');
require('../js/bots.js');

const N = +process.argv[2] || 400;
function duel(a, b, n) {
  let wa = 0, sa = 0, sb = 0;
  for (let g = 0; g < n; g++) {
    const flip = g % 2 === 1;
    const players = flip ? [{ name: 'B', bot: b }, { name: 'A', bot: a }] : [{ name: 'A', bot: a }, { name: 'B', bot: b }];
    const s = E.newGame({ seed: 50000 + g * 104729, players });
    const ia = flip ? 1 : 0;
    const w = s.result.winners;
    if (w.indexOf(ia) >= 0) wa += 1 / w.length;
    sa += s.result.scores[ia].total; sb += s.result.scores[1 - ia].total;
  }
  return { win: wa / n, avgA: sa / n, avgB: sb / n };
}
function table(level, n) {
  let w = 0;
  for (let g = 0; g < n; g++) {
    const seat = g % 4;
    const players = Array.from({ length: 4 }, (_, i) => ({ name: 'P' + i, bot: i === seat ? 'hard' : level }));
    const s = E.newGame({ seed: 90000 + g * 7919, players });
    if (s.result.winners.indexOf(seat) >= 0) w += 1 / s.result.winners.length;
  }
  return w / n;
}
const t0 = Date.now();
const he = duel('hard', 'easy', N); console.log('hard vs easy', he);
const hm = duel('hard', 'medium', N); console.log('hard vs medium', hm);
const me = duel('medium', 'easy', N); console.log('medium vs easy', me);
const t4m = table('medium', Math.round(N / 2)); console.log('hard at a table of 3 medium', t4m, '(fair share 25%)');
const pc = x => Math.round(x * 100) + '%';
const out = { games: (N * 3 + Math.round(N / 2)).toLocaleString('en-US'), date: new Date().toISOString().slice(0, 10),
  hardEasy: pc(he.win), hardMedium: pc(hm.win), mediumEasy: pc(me.win), hardTable4: pc(t4m),
  raw: { he, hm, me, t4m } };
fs.writeFileSync(path.join(__dirname, '..', 'js', 'strength-data.js'), '/* generated by tools/measure-levels.js — do not edit by hand */\nwindow.EvoStrength = ' + JSON.stringify(out) + ';\n');
console.log('done in', ((Date.now() - t0) / 1000).toFixed(0) + 's');
