// Simulates Hard-vs-Hard games and writes js/lab-data.js (trait food rates, trait-pair lift,
// watering-hole food by player count). Run: node tools/build-lab.js [games]   (~1 s per 4-player game)
const fs = require('fs');
const path = require('path');
const Cards = require('../js/cards.js');
const E = require('../js/engine.js');
require('../js/bots.js');

const N = +process.argv[2] || 600;
const MIN_N = 40;
const sums = {};      // trait-set key -> [food sum, species-rounds]
const lifeBy = {};    // trait -> [life sum, count]
let base = [0, 0], baseLife = [0, 0];
const holeBy = {};    // players -> [food added sum, rounds]
const t0 = Date.now();
for (let g = 0; g < N; g++) {
  const n = 2 + (g % 4); // 2..5 players
  const players = Array.from({ length: n }, (_, i) => ({ name: 'H' + i, bot: 'hard' }));
  const s = E.newGame({ seed: 1000 + g * 7919, players, trace: true });
  for (const [key, food] of s.trace.rounds) {
    (sums[key] = sums[key] || [0, 0]);
    sums[key][0] += food; sums[key][1]++;
    base[0] += food; base[1]++;
  }
  for (const [key, life] of s.trace.life) {
    baseLife[0] += life; baseLife[1]++;
    for (const t of key ? key.split('|') : []) { (lifeBy[t] = lifeBy[t] || [0, 0]); lifeBy[t][0] += life; lifeBy[t][1]++; }
  }
  for (const h of s.hist) { (holeBy[n] = holeBy[n] || [0, 0]); holeBy[n][0] += Math.max(0, h.added); holeBy[n][1]++; }
  if (g % 100 === 99) console.log(g + 1, 'games', ((Date.now() - t0) / 1000).toFixed(0) + 's');
}
// per trait and per pair: species-rounds whose trait set contains it
const traitF = {}, pairF = {};
for (const key in sums) {
  const ts = key ? key.split('|') : [];
  const [f, c] = sums[key];
  for (const t of ts) { (traitF[t] = traitF[t] || [0, 0]); traitF[t][0] += f; traitF[t][1] += c; }
  for (let i = 0; i < ts.length; i++) for (let j = i + 1; j < ts.length; j++) {
    const k = [ts[i], ts[j]].sort().join('|');
    (pairF[k] = pairF[k] || [0, 0]); pairF[k][0] += f; pairF[k][1] += c;
  }
}
const b = base[0] / base[1];
const out = { games: N, minN: MIN_N, date: new Date().toISOString().slice(0, 10), base: { food: b, life: baseLife[0] / baseLife[1] }, traits: {}, pairs: {}, holeByN: {} };
for (const t of Cards.TRAITS) {
  const f = traitF[t], l = lifeBy[t];
  out.traits[t] = { food: f ? f[0] / f[1] : 0, n: f ? f[1] : 0, life: l ? l[0] / l[1] : 0 };
}
for (const k in pairF) {
  const [a, c] = k.split('|');
  const food = pairF[k][0] / pairF[k][1];
  const expect = b + (out.traits[a].food - b) + (out.traits[c].food - b);
  out.pairs[k] = { food: +food.toFixed(3), n: pairF[k][1], lift: +(food - expect).toFixed(3) };
}
for (const n in holeBy) out.holeByN[n] = holeBy[n][0] / holeBy[n][1];
for (const t in out.traits) { out.traits[t].food = +out.traits[t].food.toFixed(3); out.traits[t].life = +out.traits[t].life.toFixed(2); }
const file = path.join(__dirname, '..', 'js', 'lab-data.js');
fs.writeFileSync(file, '/* generated by tools/build-lab.js on ' + out.date + ' (' + N + ' Hard-vs-Hard games, 2-5 players) — do not edit by hand */\nwindow.EvoLab = ' + JSON.stringify(out) + ';\n');
console.log('wrote', file, 'base food/round', b.toFixed(2), 'in', ((Date.now() - t0) / 1000).toFixed(0) + 's');
